namespace FhirFsGen

open System
open System.IO
open System.Text
open FhirFsGen.Ir

/// Emits F# modules the server can compile or reference later.
module EmitFsharp =

    let private escape (s: string) = s.Replace("\"", "\\\"")

    let writeCatalog (manifest: GenerationManifest) (path: string) =
        Directory.CreateDirectory(Path.GetDirectoryName path) |> ignore
        let sb = StringBuilder()

        sb.AppendLine("// <auto-generated />")
        |> ignore

        sb.AppendLine($"// FHIR {manifest.FhirVersion} — generated {manifest.GeneratedAtUtc} UTC")
        |> ignore

        sb.AppendLine("namespace FhirServer.Schemas") |> ignore
        sb.AppendLine() |> ignore
        sb.AppendLine("/// Resource catalog produced by Generator/FhirFsGen (R5).")
        |> ignore

        sb.AppendLine("module GeneratedResourceCatalog =") |> ignore
        sb.AppendLine() |> ignore
        sb.AppendLine($"    let fhirVersion = \"{escape manifest.FhirVersion}\"")
        |> ignore

        sb.AppendLine() |> ignore
        sb.AppendLine("    let supportedResourceTypes =") |> ignore
        sb.AppendLine("        [") |> ignore

        for r in manifest.Resources do
            sb.AppendLine($"          \"{escape r.TypeName}\"") |> ignore

        sb.AppendLine("        ]") |> ignore
        sb.AppendLine() |> ignore

        sb.AppendLine("    let schemaRelativePath (resourceType: string) =")
        |> ignore

        sb.AppendLine("        $\"schemas/{resourceType}.schema.json\"")
        |> ignore

        File.WriteAllText(path, sb.ToString(), Encoding.UTF8)

    let writeTodoMarkdown (allTypes: string list) (doneTypes: Set<string>) (path: string) =
        Directory.CreateDirectory(Path.GetDirectoryName path) |> ignore
        let sb = StringBuilder()

        sb.AppendLine("# FHIR R5 resource generation TODO") |> ignore
        sb.AppendLine() |> ignore

        sb.AppendLine(
            "Source index: [hl7.org/fhir/resourcelist.html](https://hl7.org/fhir/resourcelist.html) (R5 / v5.0.0)."
        )
        |> ignore

        sb.AppendLine(
            "One checkbox per concrete resource type from `hl7.fhir.r5.core` (kind=resource, specialization)."
        )
        |> ignore

        sb.AppendLine() |> ignore
        let generatedAt = DateTime.UtcNow.ToString("yyyy-MM-dd")
        sb.AppendLine($"Generated: {generatedAt} UTC") |> ignore
        sb.AppendLine() |> ignore

        let doneCount = allTypes |> List.filter doneTypes.Contains |> List.length
        sb.AppendLine($"Progress: **{doneCount} / {allTypes.Length}**") |> ignore
        sb.AppendLine() |> ignore

        for name in allTypes do
            let mark = if doneTypes.Contains name then "x" else " "
            sb.AppendLine($"- [{mark}] {name}") |> ignore

        File.WriteAllText(path, sb.ToString(), Encoding.UTF8)
